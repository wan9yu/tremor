"""Robust per-line normalization for tremor.

Each line is normalized ON ITS OWN with a rolling robust z-score (median for the
centre, Rousseeuw-Croux Qn for the scale — both shrug off outliers far better
than mean + standard deviation). Lines are NEVER combined into a single doom
score — the only composite tremor reports is a COUNT of how many lines are
trembling on a given day.
"""
import statistics
from datetime import date, datetime, timedelta
from itertools import combinations

WINDOW = 90        # rolling baseline: the last 90 available readings
MAX_AGE_DAYS = 180  # calendar cap: slow sources must not build baselines across seasons
THRESHOLD = 3.0    # |z| above this counts as "trembling" AT A FULL WINDOW; see _C_N
MIN_POINTS = 10    # need at least this much clean history to judge honestly
DECYCLE_MIN = 70   # de-cycle a weekly-rhythm line only once the window is this deep

# A line reporting nothing can be in several very different states, and the
# instrument used to express all of them the same way: an empty z-score. That is
# how a strait closing went unnoticed for fifteen days — the only line watching
# it COULD NOT SCORE, and "cannot score" looked exactly like "calm". The state is
# now recorded as data on every row, not as prose inside source_note.
STATUS_SCORING = "scoring"      # enough clean history; a z was computed
STATUS_WARMING = "warming-up"   # fewer than MIN_POINTS unique observations yet
STATUS_STALE = "stale"          # the source republished an observation we hold
# No reading at all. TWO CAUSES, and the column does not yet separate them: the
# fetch failed, or the fetch SUCCEEDED and the fetcher refused what came back —
# IODA reporting every country it watches as dark, Yahoo quoting the two yuan
# legs six hours apart, Fingrid down and a 60-second Statnett max being the
# wrong quantity. Both are honest empties with a stated reason in source_note,
# but "the source was down" and "we declined to read this" are different facts
# and the record told them apart only in prose. The FIRST split lands in round 18
# (STABLE_SINCE 2026-08-17): a market closure — the onshore yuan simply not trading
# on a weekend — now writes ``closed`` (below) instead of dark. The rest of the
# ambiguity (a real outage vs a weekday declined read) still lives in ``dark``;
# do not read dark as "the source failed".
STATUS_DARK = "dark"
# Market closure, split from dark (round 18): a line whose underlying market is
# shut on weekends (WEEKEND_MARKET) and has no reading on a Sat/Sun is CLOSED, not
# failed — there is no observation to miss when the market is not open. It counts
# toward neither the dark nor the blind tally; weekday holidays stay dark.
STATUS_CLOSED = "closed"
STATUS_FLAT = "no-spread"       # history has no resolvable dispersion to judge against
# A line is BLIND when it holds a reading it cannot judge. Dark is not blindness
# (it is already reported loudly); staleness is not either (the observation was
# judged when it first arrived).
BLIND_STATUSES = (STATUS_WARMING, STATUS_FLAT)


